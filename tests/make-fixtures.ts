// Writes tests/fixtures/layouts.json: expected layouts from the TypeScript, for the native checks.
import { writeFileSync } from "node:fs";
import { Ring, tableLayout } from "../implementation/web/layout.ts";
import type { Orientation } from "../implementation/web/layout.ts";

export const SCREENS: Record<Orientation, { width: number; height: number }> = {
  portrait: { width: 360, height: 468 },
  landscape: { width: 1280, height: 720 },
  tv: { width: 1920, height: 1080 },
};

export function build(): string {
  const layouts = [];
  for (const orientation of ["portrait", "landscape", "tv"] as Orientation[]) for (let seats = 2; seats <= 9; seats++) {
    layouts.push({ orientation, seats, ...SCREENS[orientation], layout: tableLayout({ seats, orientation, ...SCREENS[orientation] }) });
  }
  layouts.push({ orientation: "landscape", seats: 5, width: 700, height: 900, turn: 0.2, layout: tableLayout({ seats: 5, orientation: "landscape", width: 700, height: 900, turn: 0.2 }) });
  const ring = new Ring(400, 250);
  const rings = [0, 0.1, 0.37, 0.5, 0.83].map((f) => ({ fraction: f, angle: ring.angle(f), toward: ring.fractionToward(ring.point(ring.angle(f)), { x: 0, y: 0 }) }));
  return JSON.stringify({ layouts, ring: { rx: 400, ry: 250, rings } }, null, 1) + "\n";
}

// The same layouts as Kotlin source rows, so the Android check needs no JSON library.
export function buildKotlin(): string {
  const d = JSON.parse(build());
  const num = (v: number) => (Number.isInteger(v) ? v.toFixed(1) : String(v));
  const rows = d.layouts.map((it: any) => {
    const l = it.layout, s1 = l.seatSpots[1], sl = l.seatSpots[l.seatSpots.length - 1];
    return `    arrayOf<Any>("${it.orientation}", ${it.seats}, ${num(it.width)}, ${num(it.height)}, ${num(it.turn ?? 0)}, ${[s1.x, s1.y, s1.angle, sl.x, sl.y, l.pot.x, l.pot.y, l.board[4].x, l.deck.x].map(num).join(", ")}),`;
  });
  return `// Generated by tests/make-fixtures.ts from the TypeScript layouts: one row per layout.
// orientation, seats, width, height, turn, seat 1 x, y, angle, last seat x, y, pot x, y, board 5 x, deck x
val EXPECTED = listOf(
${rows.join("\n")}
)
`;
}

if (import.meta.main) {
  writeFileSync(new URL("fixtures/layouts.json", import.meta.url), build());
  writeFileSync(new URL("android/Expected.kt", import.meta.url), buildKotlin());
}
